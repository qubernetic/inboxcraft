#[test]
fn the_check_passes_after_writing_the_sources() {
    let dir = fixture();
    let mut out = Vec::new();
    assert!(gate(dir.path(), false, &mut out).unwrap());
    assert_eq!(String::from_utf8(out).unwrap(), format!("flatpak-sources: wrote {SOURCES} for 2 crates\n"));
    let (passed, out) = check(dir.path());
    assert!(passed, "{out}");
    assert_eq!(out, format!("flatpak-sources-check: {SOURCES} matches Cargo.lock (2 crates)\n"));
}

#[test]
fn the_check_fails_on_a_lock_change_without_regenerated_sources() {
    let dir = fixture();
    gate(dir.path(), false, &mut Vec::new()).unwrap();
    write(dir.path(), "Cargo.lock", &lock(&[("accesskit", "0.25.3", SUM_B), ("zerocopy", "0.8.1", SUM_B)]));
    let (passed, out) = check(dir.path());
    assert!(!passed);
    assert_eq!(out, format!("flatpak-sources-check: {SOURCES} does not match Cargo.lock; run `just flatpak-sources` and commit it\n"));
    gate(dir.path(), false, &mut Vec::new()).unwrap();
    assert!(check(dir.path()).0, "regenerating fixes it");
}

#[test]
fn the_check_fails_when_the_sources_are_missing() {
    let dir = fixture();
    let (passed, out) = check(dir.path());
    assert!(!passed);
    assert_eq!(out, format!("flatpak-sources-check: {SOURCES} is missing; run `just flatpak-sources` and commit it\n"));
}

#[test]
fn a_lock_that_cannot_be_read_or_turned_into_sources_is_an_error() {
    let dir = tempfile::tempdir().unwrap();
    assert!(matches!(gate(dir.path(), true, &mut Vec::new()), Err(Error::Io { .. })));
    write(dir.path(), "Cargo.lock", "version = 4\n");
    let error = gate(dir.path(), true, &mut Vec::new()).unwrap_err();
    assert_eq!(error.to_string(), format!("{}: Cargo.lock lists no packages", dir.path().join("Cargo.lock").display()));
}

