const CRATES_IO: &str = "registry+https://github.com/rust-lang/crates.io-index";
const SUM_A: &str = "4e883d1d28c5fd5568c79ed2d2bd48d9f2fd3945c8974ed0f53690ceddb051be";
const SUM_B: &str = "24f5baf62e34a4a6c30e3d697e4782f821a7337049c44c3b40576a27dfbb580d";

/// A lock file with the workspace crate `app` and the crates.io crates in `crates` (name, version, checksum).
fn lock(crates: &[(&str, &str, &str)]) -> String {
    let mut text = "# This file is automatically @generated by Cargo.\nversion = 4\n\n[[package]]\nname = \"app\"\nversion = \"0.1.0\"\n".to_owned();
    for (name, version, sum) in crates {
        text.push_str(&format!("\n[[package]]\nname = \"{name}\"\nversion = \"{version}\"\nsource = \"{CRATES_IO}\"\nchecksum = \"{sum}\"\n"));
    }
    text
}

fn fixture() -> tempfile::TempDir {
    let dir = tempfile::tempdir().unwrap();
    write(dir.path(), "Cargo.lock", &lock(&[("accesskit", "0.25.2", SUM_A), ("zerocopy", "0.8.1", SUM_B)]));
    dir
}

fn check(root: &std::path::Path) -> (bool, String) {
    let mut out = Vec::new();
    let passed = gate(root, true, &mut out).unwrap();
    (passed, String::from_utf8(out).unwrap())
}

#[test]
fn every_crates_io_package_becomes_an_archive_and_its_checksum_file() {
    let json = sources(&lock(&[("accesskit", "0.25.2", SUM_A)])).unwrap();
    let expected = format!(
        r#"[
  {{
    "type": "archive",
    "archive-type": "tar-gzip",
    "url": "https://static.crates.io/crates/accesskit/accesskit-0.25.2.crate",
    "sha256": "{SUM_A}",
    "dest": "cargo/vendor/accesskit-0.25.2"
  }},
  {{
    "type": "inline",
    "contents": "{{\"package\": \"{SUM_A}\", \"files\": {{}}}}",
    "dest": "cargo/vendor/accesskit-0.25.2",
    "dest-filename": ".cargo-checksum.json"
  }},
  {{
    "type": "inline",
    "contents": "[source.vendored-sources]\ndirectory = \"cargo/vendor\"\n\n[source.crates-io]\nreplace-with = \"vendored-sources\"\n\n[net]\noffline = true\n",
    "dest": "cargo",
    "dest-filename": "config.toml"
  }}
]
"#
    );
    assert_eq!(json, expected);
}

#[test]
fn workspace_crates_need_no_source_and_the_order_follows_the_lock() {
    let json = sources(&lock(&[("b", "1.0.0", SUM_A), ("a", "2.0.0", SUM_B)])).unwrap();
    assert!(!json.contains("/app-0.1.0"), "{json}");
    let b = json.find("crates/b/b-1.0.0.crate").unwrap();
    let a = json.find("crates/a/a-2.0.0.crate").unwrap();
    assert!(b < a, "{json}");
}

#[test]
fn the_sparse_index_is_crates_io_too() {
    let text = lock(&[("a", "1.0.0", SUM_A)]).replace(CRATES_IO, "sparse+https://index.crates.io/");
    assert!(sources(&text).unwrap().contains("crates/a/a-1.0.0.crate"));
}

#[test]
fn other_sources_are_refused() {
    let git = lock(&[("a", "1.0.0", SUM_A)]).replace(CRATES_IO, "git+https://example.org/a.git#0123");
    assert_eq!(sources(&git), Err("a 1.0.0 comes from git+https://example.org/a.git#0123, not crates.io".to_owned()));
    let other = lock(&[("a", "1.0.0", SUM_A)]).replace(CRATES_IO, "registry+https://example.org/index");
    assert!(sources(&other).unwrap_err().contains("not crates.io"));
}

#[test]
fn hostile_names_versions_and_checksums_are_refused() {
    for (name, version, sum, says) in [
        ("../evil", "1.0.0", SUM_A, "name"),
        ("a/b", "1.0.0", SUM_A, "name"),
        ("", "1.0.0", SUM_A, "name"),
        ("a b", "1.0.0", SUM_A, "name"),
        ("a", "1.0.0/..", SUM_A, "version"),
        ("a", "..", SUM_A, "version"),
        ("a", "1.0.0", "abc", "checksum"),
        ("a", "1.0.0", &SUM_A.replace('4', "G"), "checksum"),
    ] {
        let error = sources(&lock(&[(name, version, sum)])).unwrap_err();
        assert!(error.contains(says), "{name} {version} {sum}: {error}");
    }
}

#[test]
fn a_registry_package_without_a_checksum_is_refused() {
    let text = format!("version = 4\n\n[[package]]\nname = \"a\"\nversion = \"1.0.0\"\nsource = \"{CRATES_IO}\"\n");
    assert_eq!(sources(&text), Err("a 1.0.0 has no checksum".to_owned()));
}

#[test]
fn a_broken_lock_file_is_refused() {
    assert!(sources("[[package]\n").unwrap_err().starts_with("Cargo.lock: "));
    assert_eq!(sources("version = 4\n"), Err("Cargo.lock lists no packages".to_owned()));
    assert_eq!(sources("package = 3\n"), Err("Cargo.lock lists no packages".to_owned()));
    assert_eq!(sources("package = [3]\n"), Err("Cargo.lock: package 1 is not a table".to_owned()));
    assert_eq!(sources("[[package]]\nversion = \"1\"\n"), Err("Cargo.lock: package 1 has no name".to_owned()));
    assert_eq!(sources("[[package]]\nname = \"a\"\n"), Err("Cargo.lock: package 1 has no version".to_owned()));
    assert_eq!(sources("[[package]]\nname = \"a\"\nversion = \"1\"\nsource = 3\n"), Err("Cargo.lock: a 1 has a source that is not text".to_owned()));
}

