//! What kind of character a character is, by its Unicode general category: what a question keeps of the data it
//! quotes ([`crate::owner_request::data`]) is chosen by kind, an allow list, not by a list of marks to leave out.

/// The kind of a character, from its general category in Unicode 15.1.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum Class {
    /// A letter (`Lu`, `Ll`, `Lt`, `Lo`), but no modifier letter.
    Letter,
    /// A combining mark (`Mn`, `Mc`, `Me`).
    Mark,
    /// A number (`Nd`, `Nl`, `No`).
    Number,
    /// Punctuation (`Pc`, `Pd`, `Ps`, `Pe`, `Po`), but no initial or final quote.
    Punctuation,
    /// A symbol (`Sm`, `Sc`, `So`), but no modifier symbol.
    Symbol,
    /// A mark that stands by itself and can pass for a quote: an initial or final quote (`Pi`, `Pf`), a modifier
    /// letter (`Lm`) or a modifier symbol (`Sk`).
    QuoteLike,
    /// Anything else: separators, controls, format characters, surrogates, private use, unassigned.
    Other,
}

/// The kind of `c`.
#[must_use]
pub(crate) fn class(c: char) -> Class {
    let code = u32::from(c);
    let after = RUNS.partition_point(|run| run >> 3 <= code);
    match after.checked_sub(1).and_then(|at| RUNS.get(at)).map(|run| run & 7) {
        Some(1) => Class::Letter,
        Some(2) => Class::Mark,
        Some(3) => Class::Number,
        Some(4) => Class::Punctuation,
        Some(5) => Class::Symbol,
        Some(6) => Class::QuoteLike,
        _ => Class::Other,
    }
}

